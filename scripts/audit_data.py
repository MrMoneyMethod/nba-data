#!/usr/bin/env python3
"""Profile every raw source and write reports/data_quality.md.

Memory-safe: large CSVs are read in chunks / with selected columns,
PlayByPlay is inspected via parquet metadata + one row group only.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw_reassembled"
REPORTS = ROOT / "reports"


def season_of(dates: pd.Series) -> pd.Series:
    y = dates.dt.year - (dates.dt.month < 10).astype(int)
    return y  # season start year


def main() -> None:
    REPORTS.mkdir(parents=True, exist_ok=True)
    lines: list[str] = ["# Data-quality audit", ""]
    lines.append("Generated by `scripts/audit_data.py` from the reassembled raw files. "
                 "All findings below were measured, not assumed.\n")

    # ---- Games -------------------------------------------------------
    games = pd.read_csv(ROOT / "Games.csv", parse_dates=["gameDateTimeEst"])
    lines += ["## Games.csv",
              f"- Rows: {len(games):,} | range: {games.gameDateTimeEst.min()} → {games.gameDateTimeEst.max()}",
              f"- gameType counts: {games.gameType.value_counts().to_dict()}",
              f"- Nulls: homeScore={games.homeScore.isna().sum()}, awayScore={games.awayScore.isna().sum()}, "
              f"attendance null share={games.attendance.isna().mean():.1%}",
              f"- Duplicate gameId: {games.gameId.duplicated().sum()}",
              f"- homeScore==awayScore (ties, impossible in NBA): {(games.homeScore == games.awayScore).sum()}",
              f"- winner != higher scorer: "
              f"{(((games.homeScore > games.awayScore) & (games.winner != games.hometeamId)) | ((games.awayScore > games.homeScore) & (games.winner != games.awayteamId))).sum()}",
              ""]

    # ---- TeamStatistics ----------------------------------------------
    team = pd.read_csv(RAW / "TeamStatistics.csv",
                         usecols=["gameId", "gameDateTimeEst", "teamId", "opponentTeamId", "home", "win",
                                  "teamScore", "opponentScore", "gameType", "numMinutes"],
                         parse_dates=["gameDateTimeEst"], low_memory=False)
    lines += ["## TeamStatistics.csv (reassembled)",
              f"- Rows: {len(team):,} (expect ~2 per game) | range: {team.gameDateTimeEst.min()} → {team.gameDateTimeEst.max()}",
              f"- Games covered: {team.gameId.nunique():,} vs Games.csv {games.gameId.nunique():,}",
              f"- Rows per game != 2: {(team.groupby('gameId').size() != 2).sum()} games",
              f"- gameType counts: {team.gameType.value_counts().to_dict()}",
              f"- Score mismatches vs Games.csv checked in build step.", ""]

    # ---- TeamStatisticsExtended ---------------------------------------
    teamx = pd.read_csv(RAW / "TeamStatisticsExtended.csv",
                          usecols=["gameId", "gameDateTimeEst", "teamId", "offensiveRating", "defensiveRating"],
                          parse_dates=["gameDateTimeEst"], low_memory=False)
    lines += ["## TeamStatisticsExtended.csv (reassembled)",
              f"- Rows: {len(teamx):,} | range: {teamx.gameDateTimeEst.min()} → {teamx.gameDateTimeEst.max()} "
              "(advanced stats only exist for the modern era — do not require them for all-history features)",
              f"- offensiveRating null share: {teamx.offensiveRating.isna().mean():.1%}", ""]

    # ---- PlayerStatistics (chunked) -----------------------------------
    total, null_pts, seasons = 0, 0, {}
    mins_zero = 0
    for chunk in pd.read_csv(RAW / "PlayerStatistics.csv",
                             usecols=["personId", "gameId", "gameDateTimeEst", "numMinutes", "points", "gameType"],
                             parse_dates=["gameDateTimeEst"], chunksize=400_000, low_memory=False):
        total += len(chunk)
        null_pts += int(chunk.points.isna().sum())
        mins_zero += int((chunk.numMinutes.fillna(0) == 0).sum())
        for y, c in season_of(chunk.gameDateTimeEst).value_counts().items():
            seasons[int(y)] = seasons.get(int(y), 0) + int(c)
    lines += ["## PlayerStatistics.csv (reassembled)",
              f"- Rows: {total:,} | distinct counting is chunked; points nulls: {null_pts:,}; "
              f"zero-minute rows (DNP): {mins_zero:,} ({mins_zero/total:.1%})",
              f"- Season-start-year coverage: min={min(seasons)}, max={max(seasons)}", ""]

    # ---- PlayByPlay (metadata + sample) -------------------------------
    pf = pq.ParquetFile(RAW / "PlayByPlay.parquet")
    cols = pf.schema_arrow.names
    lines += ["## PlayByPlay.parquet (reassembled)",
              f"- Rows: {pf.metadata.num_rows:,} | Columns: {pf.metadata.num_columns} | "
              f"Row groups: {pf.metadata.num_row_groups}",
              f"- Columns: {cols}",
              "- Not used by the v1 engine (box-score rolling form captures most signal at "
              "1/100th the compute); reserved for future lineup/possession features.", ""]

    # ---- Closing lines (second upload) -------------------------------
    closing_lines = ["## Closing-lines files (nba_2024_25 / nba_2025_26_closing_lines_ats.csv)", ""]
    closers = {}
    for f in ["nba_2024_25_closing_lines_ats.csv", "nba_2025_26_closing_lines_ats.csv",
              "nba_2026_27_odds.csv"]:
        d = pd.read_csv(ROOT / f, parse_dates=["date_et"])
        closers[f] = d
        closing_lines.append(f"- `{f}`: {len(d):,} rows | {d.date_et.min().date()} → {d.date_et.max().date()} | "
                     f"season col={sorted(d.season.unique())} | types={d.season_type.value_counts().to_dict()} | "
                     f"nulls close_prob/spread/total = {d.close_home_win_prob.isna().sum()}/"
                     f"{d.close_spread_home.isna().sum()}/{d.close_total.isna().sum()}")
    a, b = closers["nba_2025_26_closing_lines_ats.csv"], closers["nba_2026_27_odds.csv"]
    same_ids = bool((a.game_id.values == b.game_id.values).all())
    same_scores = bool(((a.home_score == b.home_score) & (a.away_score == b.away_score)).all())
    closing_lines += [f"- **WARNING: `nba_2026_27_odds.csv` is a mislabeled duplicate of 2025-26** "
              f"(identical game_id order: {same_ids}; identical scores: {same_scores}; only its "
              "`season` column and bookmaker count differ). It contains no 2026-27 fixtures and "
              "is excluded from training/evaluation until a real 2026-27 file replaces it.",
              "- Join keys: `date_et` + full team names. Odds names use 'Los Angeles Clippers' "
              "while Games.csv uses 'LA Clippers' in 2025-26 (aliased in train.py). A handful of "
              "2024-25 rows do not match Games.csv on date+teams (rescheduled games) and 2 Games.csv "
              "rows carry 0-0 scores (2025-03-19 UTA-WAS, 2025-04-01 SAS-ORL; dropped as 'ties').",
              "- `NBA_Closing_Odds_SAMPLE.csv`: 20 rows from 2008, no spread/total -- not used.",
              "- Only pre-game lines (open/close win prob, spread, total) are used, for evaluation "
              "only; outcome columns (`ats_result`, `favorite_won`, `total_result`, ...) are never features.",
              ""]
    lines += closing_lines

    # ---- Odds sample ----------------------------------------------------
    odds = pd.read_csv(ROOT / "nba_game_scores_1g_2025_26_sample.csv", parse_dates=["date"])
    lines += ["## nba_game_scores_1g_2025_26_sample.csv (market sample)",
              f"- Rows: {len(odds):,} | range: {odds.date.min().date()} → {odds.date.max().date()}",
              f"- Columns: {len(odds.columns)} (includes closing + opening lines, moneylines, O/U)",
              f"- home_point_spread nulls: {odds.home_point_spread.isna().sum()}, "
              f"over_under nulls: {odds.over_under.isna().sum()}, "
              f"home_money_line nulls: {odds.home_money_line.isna().sum()}",
              "- WARNING: this file contains in-sample engineered columns such as "
              "`total_points`, `point_margin_game`, `won_on_spread`, streak/cover columns computed "
              "including the current game. Those leak the outcome and are never used as model inputs; "
              "only pre-game lines (spreads, totals, moneylines) and team/date keys are used, "
              "and only for evaluation.", ""]

    out = REPORTS / "data_quality.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out.read_text())


if __name__ == "__main__":
    main()
